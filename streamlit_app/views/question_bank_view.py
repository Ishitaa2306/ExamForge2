"""
Question Bank Explorer View.
Enables students and examiners to inspect grounded questions generated by Google Gemini,
filter by cognitive category, difficulty tier, and examine evaluation rubrics.
"""
import streamlit as st
from app.database.models import (
    DifficultyLevel,
    Document,
    DocumentStatus,
    DocumentTopic,
    QuestionBank,
    QuestionCategory,
)
from streamlit_app.state import get_current_user_id, get_db_session


def render_question_bank_view():
    user_id = get_current_user_id()
    if not user_id:
        st.warning("Please sign in to view question banks.")
        return

    st.markdown(
        """
        <div>
            <span class="badge badge-terracotta">Agent 2: Question Generation</span>
            <h1 style="font-size: 30px; margin-top: 6px; margin-bottom: 4px;">Grounded Question Bank</h1>
            <p style="color: var(--color-warmgray); font-size: 14px;">
                Inspect syllabus-grounded questions authored by Google Gemini across 8 cognitive categories with authoritative rubrics.
            </p>
        </div>
        """,
        unsafe_allow_html=True,
    )

    db = get_db_session()
    try:
        user_docs = (
            db.query(Document)
            .filter(Document.user_id == user_id, Document.status == DocumentStatus.ANALYZED)
            .all()
        )
        doc_options = {d.id: d.original_filename for d in user_docs}
    finally:
        db.close()

    if not doc_options:
        st.info("No analyzed documents found. Please upload and analyze a PDF document first.")
        return

    default_id = st.session_state.get("selected_doc_id")
    if default_id not in doc_options:
        default_id = list(doc_options.keys())[0]

    # Filters Row
    f_col1, f_col2, f_col3, f_col4 = st.columns(4)

    with f_col1:
        selected_doc = st.selectbox(
            "Document",
            options=list(doc_options.keys()),
            format_func=lambda x: doc_options[x],
            index=list(doc_options.keys()).index(default_id) if default_id in doc_options else 0,
        )

    db = get_db_session()
    try:
        topics = db.query(DocumentTopic).filter(DocumentTopic.document_id == selected_doc).all()
        topic_options = {0: "All Topics"} | {t.id: t.name for t in topics}

        with f_col2:
            selected_topic = st.selectbox(
                "Topic",
                options=list(topic_options.keys()),
                format_func=lambda x: topic_options[x],
            )

        with f_col3:
            categories = ["All Categories"] + [c.value for c in QuestionCategory]
            selected_cat = st.selectbox("Category", options=categories)

        with f_col4:
            difficulties = ["All Difficulties"] + [d.value for d in DifficultyLevel]
            selected_diff = st.selectbox("Difficulty", options=difficulties)

        # Query questions
        query = db.query(QuestionBank).filter(QuestionBank.document_id == selected_doc)
        if selected_topic != 0:
            query = query.filter(QuestionBank.topic_id == selected_topic)
        if selected_cat != "All Categories":
            query = query.filter(QuestionBank.category == QuestionCategory(selected_cat))
        if selected_diff != "All Difficulties":
            query = query.filter(QuestionBank.difficulty == DifficultyLevel(selected_diff))

        questions = query.order_by(QuestionBank.id.asc()).all()
        total_found = len(questions)

        st.caption(f"Showing **{total_found}** question{'s' if total_found != 1 else ''} matching active filters.")

        if not questions:
            st.info("No questions found matching your filter criteria.")
        else:
            for q in questions:
                diff_val = q.difficulty.value if hasattr(q.difficulty, "value") else str(q.difficulty)
                cat_val = q.category.value if hasattr(q.category, "value") else str(q.category)
                diff_badge = "badge-sage" if diff_val == "EASY" else "badge-olive" if diff_val == "MEDIUM" else "badge-terracotta"

                with st.expander(f"[{diff_val}] [{cat_val}] {q.question_text[:100]}...", expanded=False):
                    st.markdown(f"**Question:**\n> {q.question_text}")

                    st.markdown(
                        f"""
                        <div style="display: flex; gap: 8px; margin: 10px 0;">
                            <span class="badge {diff_badge}">{diff_val}</span>
                            <span class="badge badge-sand">{cat_val}</span>
                            <span class="badge badge-sand">Source Pages: {q.source_pages or '1'}</span>
                            <span class="badge {'badge-sage' if q.is_used else 'badge-sand'}">{'Previously Asked' if q.is_used else 'Available'}</span>
                        </div>
                        """,
                        unsafe_allow_html=True,
                    )

                    if q.expected_answer_points:
                        st.markdown("**Expected Key Points:**")
                        for pt in q.expected_answer_points:
                            st.markdown(f"- {pt}")

                    if q.evaluation_rubric and isinstance(q.evaluation_rubric, dict):
                        st.markdown("**Evaluation Rubric:**")
                        for k, v in q.evaluation_rubric.items():
                            st.markdown(f"- **{k.title()}:** {v}")
    finally:
        db.close()
